package network

import (
	"fmt"
	"os"
	"strings"

	"peakroute/internal/config"
)

const DefaultInterfacesPath = "/etc/network/interfaces"

// GenerateInterfaces renders an /etc/network/interfaces configuration string from NetworkConfig
func GenerateInterfaces(cfg *config.NetworkConfig) string {
	var sb strings.Builder

	sb.WriteString("# Automatically generated by PeakRoute OS. Do not edit directly.\n\n")
	sb.WriteString("auto lo\niface lo inet loopback\n\n")

	// WAN Interface Configuration
	if cfg.WanInterface != "" {
		sb.WriteString(fmt.Sprintf("# WAN Interface (%s)\n", cfg.WanInterface))
		sb.WriteString(fmt.Sprintf("auto %s\n", cfg.WanInterface))

		if strings.ToLower(cfg.WanMode) == "static" && cfg.WanIP != "" {
			sb.WriteString(fmt.Sprintf("iface %s inet static\n", cfg.WanInterface))
			sb.WriteString(fmt.Sprintf("  address %s\n", cfg.WanIP))
			if cfg.WanSubnet != "" {
				sb.WriteString(fmt.Sprintf("  netmask %s\n", cfg.WanSubnet))
			} else {
				sb.WriteString("  netmask 255.255.255.0\n")
			}
			if cfg.WanGateway != "" {
				sb.WriteString(fmt.Sprintf("  gateway %s\n", cfg.WanGateway))
			}
			if len(cfg.WanDNS) > 0 {
				sb.WriteString(fmt.Sprintf("  dns-nameservers %s\n", strings.Join(cfg.WanDNS, " ")))
			}
		} else {
			// Default to DHCP
			sb.WriteString(fmt.Sprintf("iface %s inet dhcp\n", cfg.WanInterface))
		}
		sb.WriteString("\n")
	}

	// Physical LAN Member Ports
	if len(cfg.LanInterfaces) > 0 {
		sb.WriteString("# LAN Member Ports\n")
		for _, iface := range cfg.LanInterfaces {
			sb.WriteString(fmt.Sprintf("auto %s\niface %s inet manual\n\n", iface, iface))
		}

		// LAN Bridge Configuration
		lanIP := cfg.LanIP
		if strings.Contains(lanIP, "/") {
			lanIP = strings.Split(lanIP, "/")[0]
		}

		netmask := cfg.LanSubnet
		if netmask == "" {
			netmask = "255.255.255.0"
		}

		sb.WriteString("# LAN Bridge (br0)\n")
		sb.WriteString("auto br0\n")
		sb.WriteString("iface br0 inet static\n")
		sb.WriteString(fmt.Sprintf("  address %s\n", lanIP))
		sb.WriteString(fmt.Sprintf("  netmask %s\n", netmask))
		sb.WriteString(fmt.Sprintf("  bridge_ports %s\n", strings.Join(cfg.LanInterfaces, " ")))
		sb.WriteString("  bridge_stp off\n")
		sb.WriteString("  bridge_fd 0\n\n")
	}

	// Managed Switch Ports & VLANs Configuration
	for _, sw := range cfg.ManagedSwitches {
		for _, port := range sw.Ports {
			if port.VLAN > 1 {
				vlanIface := fmt.Sprintf("br0.%d", port.VLAN)
				sb.WriteString(fmt.Sprintf("# Managed Switch %s Port %d (VLAN %d)\n", sw.SwitchID, port.Port, port.VLAN))
				sb.WriteString(fmt.Sprintf("auto %s\niface %s inet manual\n\n", vlanIface, vlanIface))
			}
		}
	}

	return sb.String()
}

// ApplyNetworkConfig writes the generated network configuration atomically to targetPath
func ApplyNetworkConfig(cfg *config.NetworkConfig, targetPath string) error {
	if targetPath == "" {
		targetPath = DefaultInterfacesPath
	}

	content := GenerateInterfaces(cfg)
	tmpPath := targetPath + ".tmp"

	if err := os.WriteFile(tmpPath, []byte(content), 0644); err != nil {
		return fmt.Errorf("failed to write temporary interface file: %w", err)
	}

	if err := os.Rename(tmpPath, targetPath); err != nil {
		return fmt.Errorf("failed to atomically update network interface file: %w", err)
	}

	return nil
}

// StartProvisioner listens for reactive JSON state changes and updates network configs automatically
func StartProvisioner(mgr *config.Manager, targetPath string) {
	go func() {
		for netCfg := range mgr.OnNetworkChange() {
			if netCfg != nil {
				_ = ApplyNetworkConfig(netCfg, targetPath)
			}
		}
	}()
}
